#!/usr/bin/env node
/**
 * Builds dist/ from src/. No dependencies.
 *
 *   node scripts/build.mjs          write dist/
 *   node scripts/build.mjs --check  fail if dist/ is out of date (CI, tests)
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, copyFileSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import { strip, variantPen, variantWheelHatch, tokensCss as compileTokens, variantCss as compileVariant, fontFaceCss, typefaceFiles, block, themeScopes, ref as tokenRef } from '../src/compile.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'src');
const check = process.argv.includes('--check');

const tokens = JSON.parse(readFileSync(join(src, 'tokens.json'), 'utf8'));
const P = tokens.prefix;
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const banner = `/* ${pkg.name} ${pkg.version} — generated by scripts/build.mjs from src/. Do not edit. */\n`;


/** "pigment.rust" / "color.ink" → "var(--cx-rust)" / "var(--cx-ink)" */
const ref = (path) => tokenRef(tokens, path);

const variantCss = (name) => compileVariant(tokens, name, tokens.variants[name], { banner });

/** @font-face rules of one self-hosted typeface (variable weight, upright + italic, latin + latin-ext). */
function typefaceCss(name) {
  const tf = tokens.typefaces[name];
  for (const { file } of typefaceFiles(name)) if (!existsSync(join(root, 'fonts', file))) throw new Error(`Typeface ${name}: missing fonts/${file}`);
  return `${banner}/* ${tf.family}, self-hosted (SIL OFL 1.1, see fonts/${tf.license}). ${tf.use ?? ''} */\n${fontFaceCss(tokens, name)}\n`;
}

const tokensCss = () => compileTokens(tokens, { banner });

function paletteCss(name) {
  const pal = strip(tokens.palettes[name]);
  const prefix = pal.prefix;
  delete pal.prefix;
  const entries = Object.entries(pal).map(([k, path]) => [`--${prefix}-${k}`, ref(path)]);
  return `${banner}/* Palette "${name}": app colour roles mapped onto Codex pigments. Needs tokens.css. */\n\n${block(themeScopes(tokens), entries)}\n`;
}

function resolvedTheme(theme) {
  const t = tokens.themes[theme];
  return { ...strip(t.color), ...strip(t.pigment) };
}

function tokensJs() {
  const data = {
    prefix: P,
    themes: { paper: resolvedTheme('paper'), dark: resolvedTheme('dark') },
    variants: Object.fromEntries(Object.entries(strip(tokens.variants ?? {})).map(([n, vt]) => [n, {
      paper: { ...strip(vt.paper.color), ...strip(vt.paper.pigment) },
      dark: { ...strip(vt.dark.color), ...strip(vt.dark.pigment) },
    }])),
    alpha: strip(tokens.alpha),
    semantic: Object.fromEntries(Object.entries(strip(tokens.semantic)).map(([k, p]) => [k, p.split('.')[1]])),
    font: strip(tokens.font),
    text: strip(tokens.text),
    tracking: strip(tokens.tracking),
    leading: strip(tokens.leading),
    space: strip(tokens.space),
    radius: strip(tokens.radius),
    size: strip(tokens.size),
    hatch: strip(tokens.hatch),
    pens: Object.fromEntries([['default', variantPen(tokens)], ...Object.keys(strip(tokens.variants ?? {})).map((n) => [n, variantPen(tokens, n)])]),
    wheelHatches: Object.fromEntries([['default', variantWheelHatch(tokens)], ...Object.keys(strip(tokens.variants ?? {})).map((n) => [n, variantWheelHatch(tokens, n)])]),
    motion: strip(tokens.motion),
    palettes: Object.fromEntries(
      Object.entries(strip(tokens.palettes)).map(([n, pal]) => [
        n,
        Object.fromEntries(Object.entries(pal).filter(([k]) => !k.startsWith('$')).map(([k, p]) => [k, k === 'prefix' ? p : p.split('.')[1]])),
      ]),
    ),
  };
  return `${banner.replace('/*', '//').replace(' */', '')}
export const tokens = Object.freeze(${JSON.stringify(data, null, 2)});

/** "rust" → "var(--${P}-rust)". Use in inline styles and SVG attributes. */
export function cssVar(name) {
  return \`var(--${P}-\${name})\`;
}

/**
 * Resolved colour for places without CSS variables (canvas, exported PNGs).
 * Accepts theme colours, pigments, semantic roles and ink strengths.
 * color('rust') → "#9c4a2f", color('ink-muted', 'dark') → "rgba(230, 216, 184, 0.7)".
 */
export function color(name, theme = 'paper', variant) {
  const t = variant ? tokens.variants[variant]?.[theme] : tokens.themes[theme];
  if (!t) throw new Error(\`Unknown theme: \${variant ? variant + '/' : ''}\${theme}\`);
  if (name in t) return t[name];
  if (name in tokens.semantic) return t[tokens.semantic[name]];
  if (name in tokens.alpha) return withAlpha(t.ink, tokens.alpha[name]);
  throw new Error(\`Unknown colour token: \${name}\`);
}

/** Colour of an app palette role: paletteColor('grow', 'nutrient-bio-grow'). */
export function paletteColor(palette, role, theme = 'paper', variant) {
  const p = tokens.palettes[palette];
  if (!p || !(role in p) || role === 'prefix') throw new Error(\`Unknown palette role: \${palette}.\${role}\`);
  return color(p[role], theme, variant);
}

/**
 * The pen a variant draws with (createPen settings). variantPen() → the
 * default look, variantPen('tide') → waves and a quill.
 *   createPen(document.body, variantPen('tide'));
 */
export function variantPen(variant) {
  const p = tokens.pens[variant ?? 'default'];
  if (!p) throw new Error(\`Unknown variant: \${variant}\`);
  return { ...p };
}

/**
 * How the journal wheel (@rafime/wheel) hatches its periods in a variant:
 *   new JournalWheel(el, { …, hatch: variantWheelHatch('tide') });
 */
export function variantWheelHatch(variant) {
  const h = tokens.wheelHatches[variant ?? 'default'];
  if (!h) throw new Error(\`Unknown variant: \${variant}\`);
  return { ...h };
}

function withAlpha(hex, a) {
  const n = parseInt(hex.slice(1), 16);
  return \`rgba(\${(n >> 16) & 255}, \${(n >> 8) & 255}, \${n & 255}, \${a})\`;
}
`;
}

