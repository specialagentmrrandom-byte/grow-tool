const read = (p) => readFileSync(join(src, p), 'utf8');
const files = new Map();
const tokensCssText = tokensCss();
const components = read('css/components.css');
const fonts = read('css/fonts.css');
const base = read('css/base.css');

files.set('tokens.css', tokensCssText);
files.set('components.css', banner + components);
files.set('codex.css', tokensCssText + '\n' + components);
files.set('base.css', banner + base);
files.set('fonts.css', banner + fonts);
files.set('all.css', [banner, fonts, tokensCssText, base, components].join('\n'));
for (const name of Object.keys(strip(tokens.palettes))) files.set(`palettes/${name}.css`, paletteCss(name));
for (const name of Object.keys(strip(tokens.variants ?? {}))) files.set(`variants/${name}.css`, variantCss(name));
for (const name of Object.keys(strip(tokens.typefaces ?? {}))) files.set(`typefaces/${name}.css`, typefaceCss(name));
files.set('tokens.js', tokensJs());
files.set('tokens.d.ts', tokensDts);
files.set('tokens.json', JSON.stringify(tokens, null, 2) + '\n');
files.set('ink.js', read('ink.js'));
files.set('compile.js', read('compile.js'));
files.set('pen.js', read('pen.js'));
files.set('pen.d.ts', penDts);
files.set('pen.css', banner + read('css/pen.css'));
files.set('compile.d.ts', compileDts);
files.set('ink.d.ts', inkDts);
files.set('icons.js', read('icons.js'));
files.set('icons.d.ts', iconsDts);
files.set('css.d.ts', `// Lets TypeScript accept side-effect imports of the stylesheets.\nexport {};\n`);
files.set('index.js', `export * from './tokens.js';\nexport * from './ink.js';\nexport * from './icons.js';\n`);
files.set('index.d.ts', `export * from './tokens.js';\nexport * from './ink.js';\nexport * from './icons.js';\n`);

const fontDir = join(root, 'fonts');
const fontFiles = readdirSync(fontDir).filter((f) => f.endsWith('.woff2') || /^OFL(-[\w-]+)?\.txt$/.test(f));

const dist = join(root, 'dist');
if (check) {
  const stale = [];
  for (const [name, content] of files) {
    const p = join(dist, name);
    if (!existsSync(p) || readFileSync(p, 'utf8') !== content) stale.push(name);
  }
  for (const f of fontFiles) if (!existsSync(join(dist, 'fonts', f))) stale.push(`fonts/${f}`);
  if (stale.length) {
    console.error(`dist/ is out of date: ${stale.join(', ')}\nRun: npm run build`);
    process.exit(1);
  }
  console.log('dist/ is up to date.');
} else {
  rmSync(dist, { recursive: true, force: true });
  for (const [name, content] of files) {
    const p = join(dist, name);
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, content);
  }
  mkdirSync(join(dist, 'fonts'), { recursive: true });
  for (const f of fontFiles) copyFileSync(join(fontDir, f), join(dist, 'fonts', f));
  console.log(`Built ${files.size + fontFiles.length} files into ${relative(process.cwd(), dist) || 'dist'}/`);
}
