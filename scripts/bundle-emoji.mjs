/**
 * Copies the emoji the app actually uses into public/emoji/, so nothing is
 * fetched from a CDN at runtime: no third-party requests, no IP addresses
 * leaving the device, and the very first load works offline.
 *
 * Reads the sources, finds every emoji sequence, copies the matching Twemoji
 * SVG out of node_modules and writes a list of what is available. Emoji that a
 * grower types into a note are not in that list and simply stay as the system's
 * own emoji — no broken images.
 *
 *   node scripts/bundle-emoji.mjs        (runs automatically before a build)
 */
import { readFile, writeFile, mkdir, rm, copyFile, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const SVG_SOURCE = join(root, 'node_modules/@twemoji/svg');
const SCRIPT_SOURCE = join(root, 'node_modules/@twemoji/api/dist/twemoji.min.js');
const OUT_DIR = join(root, 'public/emoji');
const VENDOR_DIR = join(root, 'public/vendor');

/** Emoji sequences, including variation selectors, ZWJ joins and skin tones. */
const EMOJI = /(?:[\u{1F000}-\u{1FAFF}\u{2190}-\u{21FF}\u{2300}-\u{27BF}\u{2B00}-\u{2BFF}\u{24C2}\u{25AA}-\u{25FE}\u{2600}-\u{26FF}\u{23E9}-\u{23FA}])(?:\u{FE0F}|\u{200D}[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}]|[\u{1F3FB}-\u{1F3FF}])*/gu;

async function sourceFiles(dir, out = []) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
        if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
        const path = join(dir, entry.name);
        if (entry.isDirectory()) await sourceFiles(path, out);
        else if (/\.(ts|js|css|html|md)$/.test(entry.name)) out.push(path);
    }
    return out;
}

/** Twemoji file names: code points in hex, joined by "-", with FE0F dropped unless it is a keycap. */
function fileNames(sequence) {
    const points = [...sequence].map(c => c.codePointAt(0).toString(16));
    const withSelector = points.join('-');
    const withoutSelector = points.filter(p => p !== 'fe0f').join('-');
    return [...new Set([withoutSelector, withSelector])];
}

const files = [
    ...await sourceFiles(join(root, 'src')),
    ...['index.html', 'app.html', 'help.html'].map(f => join(root, f)).filter(existsSync),
];

const sequences = new Set();
for (const file of files) {
    for (const match of (await readFile(file, 'utf8')).matchAll(EMOJI)) sequences.add(match[0]);
}

await rm(OUT_DIR, { recursive: true, force: true });
await mkdir(join(OUT_DIR, 'svg'), { recursive: true });
await mkdir(VENDOR_DIR, { recursive: true });

const available = [];
const missing = [];
for (const sequence of [...sequences].sort()) {
    const name = fileNames(sequence).find(n => existsSync(join(SVG_SOURCE, `${n}.svg`)));
    if (!name) {
        missing.push(sequence);
        continue;
    }
    await copyFile(join(SVG_SOURCE, `${name}.svg`), join(OUT_DIR, 'svg', `${name}.svg`));
    available.push(name);
}

// The list the app checks before replacing an emoji, so anything not bundled stays native
await writeFile(
    join(OUT_DIR, 'list.js'),
    `/* generated by scripts/bundle-emoji.mjs — do not edit */\nwindow.GROW_EMOJI=new Set(${JSON.stringify(available)});\n`,
);
await copyFile(SCRIPT_SOURCE, join(VENDOR_DIR, 'twemoji.min.js'));

console.log(`emoji: ${available.length} bundled, ${missing.length} without an svg${missing.length ? ` (${missing.join(' ')})` : ''}`);
